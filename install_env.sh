#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
#  تثبيت الإعدادات في موضع دائم — Shashety Pro
# ───────────────────────────────────────────────────────────────────────────
#      sudo bash install_env.sh
#
#  ── المشكلة التي يحلّها ──
#  كانت بيانات الاتصال في ‎/var/www/html/iptv/.env‎ — أي داخل المجلد الذي
#  ترفع نسخته من ويندوز. فكل رفعة تفعل واحداً من اثنين:
#
#    ① تستبدل ملف الخادم بنسختك المحلية، فتضيع كلمة مرور الإنتاج.
#    ② تعيد الملكية إلى مستخدم الـFTP، فلا يقرأه Apache.
#
#  وكلاهما ينتهي بنفس الرسالة: «خطأ في الاتصال بقاعدة البيانات».
#
#  ── الحلّ ──
#  ننقل الأسرار إلى ‎/etc/shashety/env‎ — خارج جذر الويب تماماً، فلا
#  يصله الرفع ولا يُنزَّل عبر HTTP مهما أخطأت إعدادات Apache. ويقرأه
#  الكود تلقائياً قبل ‎.env‎ (راجع دالة env في core/config.php).
#
#  ⚡ آمن للتكرار: لا يفقد إعداداً عاملاً أبداً، ويُبقي نسخة احتياطية.
# ═══════════════════════════════════════════════════════════════════════════
set -uo pipefail

R=$'\e[31m'; G=$'\e[32m'; Y=$'\e[33m'; C=$'\e[36m'; B=$'\e[1m'; N=$'\e[0m'
ok(){ printf '  %s✔%s %s\n' "$G" "$N" "$*"; }
bad(){ printf '  %s✘%s %s\n' "$R" "$N" "$*"; }
warn(){ printf '  %s⚠%s %s\n' "$Y" "$N" "$*"; }
inf(){ printf '  %s•%s %s\n' "$C" "$N" "$*"; }

APP_DIR="${APP_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)}"
DEST_DIR="/etc/shashety"
DEST="$DEST_DIR/env"
SRC="$APP_DIR/.env"

printf '\n%s%s══ تثبيت الإعدادات في موضع دائم ══%s\n\n' "$B" "$C" "$N"

if [[ $EUID -ne 0 ]]; then
    bad "شغّله بصلاحية الجذر:  sudo bash $0"
    exit 1
fi

WEBUSER="www-data"
id -u "$WEBUSER" >/dev/null 2>&1 || WEBUSER="apache"
id -u "$WEBUSER" >/dev/null 2>&1 || { bad "لم أجد مستخدم خادم الويب"; exit 1; }

# ═════════════════════════════════════════════════════════════════
#  ① من أين نأخذ القيم؟
# ═════════════════════════════════════════════════════════════════
# الترتيب مقصود: الوجهة أولاً. فلو شغّلت السكربت مرّة ثانية بعد رفعٍ
# جلب ‎.env‎ محلياً بكلمة مرور خاطئة، لا نسمح لتلك النسخة بأن تدهس
# إعداداً يعمل. الإعداد العامل يفوز دائماً.
PICK=""
if [[ -f "$DEST" ]] && grep -qE '^DB_PASS=.+' "$DEST" 2>/dev/null; then
    PICK="$DEST"
    inf "وُجد إعداد قائم في $DEST — سيُعتمد أساساً"
elif [[ -f "$SRC" ]] && grep -qE '^DB_PASS=.+' "$SRC" 2>/dev/null; then
    PICK="$SRC"
    inf "سأنقل الإعداد من $SRC"
else
    bad "لم أجد ملف إعدادات فيه DB_PASS — لا في $DEST ولا في $SRC"
    echo "     شغّل أولاً:  sudo bash $APP_DIR/fix_db_password.sh"
    exit 1
fi

# ═════════════════════════════════════════════════════════════════
#  ② هل القيم تعمل فعلاً؟ نتحقّق قبل أن نثبّتها
# ═════════════════════════════════════════════════════════════════
getv(){ grep -m1 -E "^$1=" "$2" 2>/dev/null | cut -d= -f2- | tr -d '"'"'"'\r'; }
DBH="$(getv DB_HOST "$PICK")"; DBN="$(getv DB_NAME "$PICK")"
DBU="$(getv DB_USER "$PICK")"; DBP="$(getv DB_PASS "$PICK")"
[[ -z "$DBH" ]] && DBH="localhost"

if command -v mysql >/dev/null 2>&1; then
    if MYSQL_PWD="$DBP" mysql -h "$DBH" -u "$DBU" -e "USE \`$DBN\`;" >/dev/null 2>&1; then
        ok "بيانات الاتصال صحيحة (المستخدم $DBU · القاعدة $DBN)"
    else
        bad "بيانات الاتصال في $PICK لا تعمل — لن أثبّت إعداداً معطّلاً"
        echo "     صحّحها أولاً:  sudo bash $APP_DIR/fix_db_password.sh"
        exit 1
    fi
else
    warn "عميل mysql غير مثبّت — تخطّيت التحقّق من صحّة الاتصال"
fi

# ═════════════════════════════════════════════════════════════════
#  ③ التثبيت
# ═════════════════════════════════════════════════════════════════
mkdir -p "$DEST_DIR"
chmod 750 "$DEST_DIR"
chown root:"$WEBUSER" "$DEST_DIR" 2>/dev/null

if [[ -f "$DEST" && "$PICK" != "$DEST" ]]; then
    cp -a "$DEST" "$DEST.bak.$(date +%s)"
    inf "احتفظت بنسخة من الإعداد السابق"
fi

if [[ "$PICK" != "$DEST" ]]; then
    cp "$PICK" "$DEST"
fi

# ⚠ الترتيب هنا هو نفسه الذي أوقع الموقع سابقاً حين انعكس:
#    chmod قبل chown مع كتم أخطاء chown يترك ملفاً لا يقرأه Apache،
#    فترتدّ الإعدادات بصمت. الملكية أولاً، ولا نضيّق إلا بعد نجاحها.
if chown root:"$WEBUSER" "$DEST" 2>/dev/null; then
    chmod 640 "$DEST"
else
    chown "$WEBUSER:$WEBUSER" "$DEST" 2>/dev/null && chmod 640 "$DEST" || chmod 644 "$DEST"
fi

# تحقّق فعلي بهوية خادم الويب — لا نكتفي بافتراض نجاح الأوامر
if sudo -u "$WEBUSER" test -r "$DEST"; then
    ok "$DEST — يقرأه $WEBUSER ($(stat -c '%U:%G %a' "$DEST"))"
else
    bad "$DEST لا يقرأه $WEBUSER — الصلاحيات لم تُضبط"
    exit 1
fi

# ═════════════════════════════════════════════════════════════════
#  ④ اختبار عبر PHP — بنفس مسار الكود الحقيقي
# ═════════════════════════════════════════════════════════════════
# ⚠ الاختبار قبل تحييد ‎.env‎ عمداً. الترتيب المعكوس (تحييد ثم اختبار)
#   يعني أن فشل الاختبار يتركك بلا مصدر إعدادات صالح داخل المشروع
#   وبملف خارجي غير عامل — أي عطل أسوأ ممّا بدأنا به.
#   ووجود ‎.env‎ الآن لا يفسد الاختبار: الملف الخارجي أعلى أولويةً،
#   فما نقرأه هنا هو ما سيقرأه التطبيق بعد التحييد بالضبط.
if command -v php >/dev/null 2>&1; then
    OUT="$(sudo -u "$WEBUSER" php -r '
        require "'"$APP_DIR"'/core/config.php";
        echo "المصدر: " . (defined("ENV_SOURCE") ? ENV_SOURCE : "?") . "\n";
        echo "الاتصال: " . (isset($pdo) && $pdo instanceof PDO ? "ناجح" : "فاشل") . "\n";
    ' 2>&1)"
    if grep -q 'ناجح' <<<"$OUT"; then
        ok "اختبار PHP بهوية $WEBUSER:"
        sed 's/^/       /' <<<"$OUT"
        if ! grep -qF "$DEST" <<<"$OUT"; then
            bad "الكود يقرأ من مصدر آخر لا من $DEST — أوقفت العملية"
            echo "     لن أحيّد .env ما دام الملف الخارجي غير مُعتمَد."
            exit 1
        fi
    else
        bad "اختبار PHP فشل — أُبقي كل شيء كما هو:"
        sed 's/^/       /' <<<"$OUT" | head -6
        exit 1
    fi
else
    warn "php غير متاح — لم أتحقّق من القراءة الفعلية"
fi

# ═════════════════════════════════════════════════════════════════
#  ⑤ تحييد ‎.env‎ داخل المشروع
# ═════════════════════════════════════════════════════════════════
# لا نحذفه: نعيد تسميته فقط، فيتوقّف عن التأثير ويبقى متاحاً للرجوع.
if [[ -f "$SRC" ]]; then
    mv "$SRC" "$SRC.moved.$(date +%s)"
    chmod 600 "$SRC.moved."* 2>/dev/null
    ok "نُقل $SRC جانباً — لن يعود الرفع يؤثّر على الإعدادات"
fi

printf '\n  %s%sتمّ. الإعدادات الآن خارج مجلد المشروع.%s\n' "$B" "$G" "$N"
echo "  ارفع ما شئت متى شئت — لن يمسّ $DEST شيء."
echo

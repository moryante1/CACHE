#!/bin/bash
# ============================================================
#  إعداد ZFS للتخزين المدمج مع الحماية - Ubuntu Server 22.04
#  الهدف: دمج عدة هاردات (بأحجام مختلفة) في مساحة واحدة
#         مع استمرار العمل عند تلف هارد + إمكانية التوسيع
# ============================================================
set -euo pipefail

POOL="storage"              # اسم الـ pool
MOUNT="/mnt/storage"        # مسار التركيب

# --- ألوان للطباعة ---
G='\033[0;32m'; Y='\033[1;33m'; R='\033[0;31m'; N='\033[0m'
info(){ echo -e "${G}[+]${N} $1"; }
warn(){ echo -e "${Y}[!]${N} $1"; }
err(){ echo -e "${R}[x]${N} $1"; }

# --- التحقق من صلاحية root ---
if [[ $EUID -ne 0 ]]; then err "شغّل السكربت بصلاحية root: sudo $0"; exit 1; fi

# ============================================================
# 1) تثبيت ZFS
# ============================================================
info "تثبيت حزم ZFS..."
apt-get update -qq
apt-get install -y zfsutils-linux
modprobe zfs
info "إصدار ZFS: $(zfs version | head -1)"

# ============================================================
# 2) عرض الهاردات المتاحة
# ============================================================
info "الهاردات المتصلة بالنظام:"
echo "------------------------------------------------------------"
lsblk -dpno NAME,SIZE,MODEL,TYPE | grep disk
echo "------------------------------------------------------------"
warn "هارد النظام (Ubuntu) موجود في القائمة أعلاه — لا تختره!"
warn "تحقق بأمر:  mount | grep ' / '"
ROOTDISK=$(findmnt -no SOURCE / | sed 's/[0-9]*$//;s/p$//')
warn "يبدو أن هارد النظام هو: ${ROOTDISK}  (تجنّبه)"
echo

# ============================================================
# 3) اختيار وضع الحماية
# ============================================================
cat <<'MODES'
اختر وضع الـ pool:

  1) raidz1  → دمج كل الهاردات، يتحمل تلف هارد واحد.
              (المساحة المستغلة من كل هارد = حجم أصغر هارد)
              مناسب لـ 3 هاردات أو أكثر متقاربة الحجم.

  2) mirror  → أزواج متطابقة (نسختان من كل بيانة).
              الأفضل مع الأحجام المختلفة + التوسيع المتكرر.
              يتحمل تلف هارد من كل زوج. توسّع بإضافة زوج جديد.

  3) raidz2  → يتحمل تلف هاردين. يحتاج 4 هاردات فأكثر.
MODES
read -rp "اختيارك [1/2/3]: " MODE

# ============================================================
# 4) إدخال الهاردات (استخدم /dev/disk/by-id للثبات)
# ============================================================
warn "أدخل مسارات الهاردات مفصولة بمسافة."
warn "يُفضّل استخدام /dev/disk/by-id/ لتفادي تغيّر ترتيب sdX."
info "الأسماء الثابتة المتاحة:"
ls -l /dev/disk/by-id/ | grep -v part | grep -E 'ata|wwn|scsi|nvme' || true
echo
read -rp "الهاردات (مثال: /dev/sdb /dev/sdc /dev/sdd): " -a DISKS

if [[ ${#DISKS[@]} -lt 2 ]]; then err "تحتاج هاردين على الأقل."; exit 1; fi

# --- تأكيد المسح ---
warn "سيتم مسح جميع البيانات على: ${DISKS[*]}"
read -rp "اكتب 'YES' للمتابعة: " CONFIRM
[[ "$CONFIRM" == "YES" ]] || { err "أُلغيت العملية."; exit 1; }

# ============================================================
# 5) إنشاء الـ pool
# ============================================================
case "$MODE" in
  1) VDEV="raidz1 ${DISKS[*]}" ;;
  2) # ترتيب الهاردات أزواجاً: mirror d1 d2 mirror d3 d4 ...
     if (( ${#DISKS[@]} % 2 != 0 )); then err "وضع mirror يحتاج عدداً زوجياً."; exit 1; fi
     VDEV=""
     for ((i=0; i<${#DISKS[@]}; i+=2)); do
       VDEV+=" mirror ${DISKS[i]} ${DISKS[i+1]}"
     done ;;
  3) VDEV="raidz2 ${DISKS[*]}" ;;
  *) err "اختيار غير صحيح."; exit 1 ;;
esac

info "إنشاء الـ pool '${POOL}'..."
# ashift=12 لأداء أفضل مع الأقراص الحديثة (4K)
zpool create -f -o ashift=12 \
  -O compression=lz4 \
  -O atime=off \
  -O xattr=sa \
  -O mountpoint="${MOUNT}" \
  "${POOL}" ${VDEV}

# ============================================================
# 6) إعدادات إضافية للأمان
# ============================================================
# فحص دوري تلقائي للبيانات (scrub) كل أسبوع
cat > /etc/cron.d/zfs-scrub <<EOF
0 3 * * 0 root /usr/sbin/zpool scrub ${POOL}
EOF

# تفعيل مراقبة الأحداث (تنبيه عند تلف هارد)
systemctl enable --now zfs-zed.service 2>/dev/null || true

info "تم! حالة الـ pool:"
zpool status "${POOL}"
echo
zfs list "${POOL}"
echo
info "التخزين جاهز على: ${MOUNT}"
info "لإضافة أزواج/هاردات لاحقاً:"
echo "   zpool add ${POOL} mirror /dev/disk/by-id/DISK1 /dev/disk/by-id/DISK2"
info "عند تلف هارد، استبدله بـ:"
echo "   zpool replace ${POOL} OLD_DISK NEW_DISK"
